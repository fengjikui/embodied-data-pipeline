// Optional browser QA. Set PLAYWRIGHT_MODULE to an installed playwright entrypoint.
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const output = resolve(process.argv[2] || '.build/industrial-report-qa');
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ headless: true, ...(process.env.REPORT_BROWSER_EXECUTABLE ? { executablePath: process.env.REPORT_BROWSER_EXECUTABLE } : {}) });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errors = [], remoteRequests = [];
page.on('pageerror', err => errors.push(err.message));
page.on('request', request => { if (/^https?:/.test(request.url())) remoteRequests.push(request.url()); });
function assert(condition, message) { if (!condition) throw new Error(message); }
const checks = {};
try {
  await page.goto(pathToFileURL(resolve('deliverables/industrial-report.html')).href);
  const sections = page.locator('.chapter details');
  assert(await sections.count() === 7, 'Seven technical chapters required');
  assert(await page.locator('.chapter details[open]').count() === 0, 'Overview must begin collapsed');
  await page.locator('#deep').click();
  assert(await page.locator('.chapter details[open]').count() === 7, 'Technical mode must expand all chapters');
  await page.locator('#brief').click();
  assert(await page.locator('.chapter details[open]').count() === 0, 'Overview must collapse chapters');
  checks.mode_buttons = true;
  await page.locator('#scenario').selectOption('moving');
  assert((await page.locator('#scene-title').innerText()).includes('持工具'), 'Moving scenario must render');
  await page.locator('#scenario').selectOption('diy');
  assert((await page.locator('#scene-data').innerText()).includes('自造'), 'DIY data must render');
  await page.locator('#scenario').selectOption('station');
  checks.scenario_switching = true;
  const missingAnchors = await page.evaluate(() => [...document.querySelectorAll('a[href^="#"]')].map(a=>a.getAttribute('href').slice(1)).filter(id=>!document.getElementById(id)));
  assert(missingAnchors.length === 0, 'All chapter anchors must resolve');
  checks.anchor_targets = true;
  await page.screenshot({ path: resolve(output, 'desktop.png') });
  await page.locator('a[href="#chapter-2"]').first().click();
  await page.locator('#chapter-2 summary').click();
  await page.screenshot({ path: resolve(output, 'model-section.png') });
  const previous = await sections.evaluateAll(nodes => nodes.map(n=>n.open));
  await page.evaluate(()=>window.dispatchEvent(new Event('beforeprint')));
  assert(await page.locator('.chapter details[open]').count() === 7, 'Print must expose full content');
  await page.evaluate(()=>window.dispatchEvent(new Event('afterprint')));
  const restored = await sections.evaluateAll(nodes => nodes.map(n=>n.open));
  assert(JSON.stringify(previous) === JSON.stringify(restored), 'Print must restore user reading state');
  checks.print_state_restore = true;
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(pathToFileURL(resolve('deliverables/industrial-report.html')).href);
  let overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert(!overflow, 'Mobile overview may not overflow');
  await page.screenshot({ path: resolve(output, 'mobile.png') });
  await page.locator('#deep').click();
  overflow = await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert(!overflow, 'Technical tables must scroll inside wrappers');
  checks.mobile_overview_and_detail_no_document_overflow = true;
  assert(errors.length===0,'No runtime JS errors');
  assert(remoteRequests.length===0,'Report may not request remote runtime assets');
  checks.no_remote_assets_or_js_errors = true;
  const sha256 = path => createHash('sha256').update(readFileSync(path)).digest('hex');
  const report = { checked_on: '2026-10-14', html_sha256: sha256('deliverables/industrial-report.html'), qa_script_sha256: sha256('scripts/verify_industrial_report.mjs'), browser: browser.version(), desktop: [1440,1100], mobile: [390,844], checks, errors, remoteRequests, screenshot_directory: output, scope: 'Offline HTML interactions and layout; not model or robot capability validation' };
  writeFileSync(resolve(output,'browser-qa.json'), JSON.stringify(report,null,2)+'\n');
  console.log(JSON.stringify(report));
} finally { await browser.close(); }
